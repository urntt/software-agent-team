"""Staged, verified, and rollback-safe managed application activation.

This package provides atomic installation, upgrade, rollback, and lifecycle
management for the software-agent-team (SAT) runtime, including Docker image handoff
and verification.

Modular Architecture:
- `constants`: Path defaults, environment variables, timeouts, error classes,
  and failure formatters.
- `models`: Pydantic schemas and dataclasses for markers, release targets,
  paths, and image transitions.
- `utils`: File locks, atomic file transactions, fsync directory operations,
  and subprocess execution.
- `markers`: Release application markers, lifecycle root markers, and
  destination validation.
- `sandbox`: Docker engine identity verification, image lineage inspection,
  and mutable tag handoffs.
- `staging`: Depth-1 git clone, package version validation, schema preflights,
  and candidate staging.
- `activation`: Application symlink swapping, launcher generation, task leases,
  and automatic rollback.
"""

